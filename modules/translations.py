# ============================================================

def localize_number(value, language):
    value = str(value)
    code = get_language_key(language)

    numeral_maps = {
        "en": str.maketrans("0123456789", "0123456789"),
        "hi": str.maketrans("0123456789", "०१२३४५६७८९"),
        "bn": str.maketrans("0123456789", "০১২৩৪৫৬৭৮৯"),
        "as": str.maketrans("0123456789", "০১২৩৪৫৬৭৮৯"),
        "mr": str.maketrans("0123456789", "०१२३४५६७८९"),
    }

    trans = numeral_maps.get(code, numeral_maps["en"])
    return value.translate(trans)

