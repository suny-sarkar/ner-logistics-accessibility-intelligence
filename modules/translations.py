def get_language_key(lang_identifier):
    """
    Normalizes any language identifier (2-letter code, English name, native script)
    to the standard language code: 'en', 'hi', 'bn', 'as', 'mr'.
    Defaults to 'en'.
    """
    if not lang_identifier:
        return "en"

    clean = str(lang_identifier).strip().lower()
    mapping = {
        "en": "en", "english": "en",
        "hi": "hi", "hindi": "hi", "हिन्दी": "hi",
        "bn": "bn", "bengali": "bn", "বাংলা": "bn",
        "as": "as", "assamese": "as", "অসমীয়া": "as",
        "mr": "mr", "marathi": "mr", "मराठी": "mr"
    }
    raw = str(lang_identifier).strip()
    return mapping.get(clean, mapping.get(raw, "en"))

def get_language_display_name(lang_identifier):
    """
    Returns the native display name for the language dropdown:
    'English', 'हिन्दी', 'বাংলা', 'অসমীয়া', 'मराठी'.
    """
    code = get_language_key(lang_identifier)
    display_map = {
        "en": "English",
        "hi": "हिन्दी",
        "bn": "বাংলা",
        "as": "অসমীয়া",
        "mr": "मराठी"
    }
    return display_map.get(code, "English")

def get_language_english_name(lang_identifier):
    """
    Returns the English name for the language:
    'English', 'Hindi', 'Bengali', 'Assamese', 'Marathi'.
    """
    code = get_language_key(lang_identifier)
    english_map = {
        "en": "English",
        "hi": "Hindi",
        "bn": "Bengali",
        "as": "Assamese",
        "mr": "Marathi"
    }
    return english_map.get(code, "English")


